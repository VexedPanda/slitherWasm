// Builds the Rust core (wasm/) and embeds it in src/wasm/slitherCoreWasm.ts, so it can be instantiated synchronously
// (the solver is called synchronously from workers and the main thread) without a separate fetch.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown'], {
  cwd: join(root, 'wasm'),
  stdio: 'inherit',
});

const bytes = readFileSync(join(root, 'wasm/target/wasm32-unknown-unknown/release/slither_core.wasm'));

writeFileSync(
  join(root, 'src/wasm/slitherCoreWasm.ts'),
  `// Generated by bin/build-wasm.js from wasm/ (do not edit)\nexport const slitherCoreWasmBase64 =\n  '${bytes.toString('base64')}';\n`,
);
console.log(`Embedded ${bytes.length} bytes of WebAssembly`);
